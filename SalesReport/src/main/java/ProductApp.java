    private void jButtonProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonProcessActionPerformed
        // TODO add your handling code here:
        String customerName = txtCustomerName.getText().trim();
        String product = jComboBoxProduct.getSelectedItem().toString();
        String priceText = txtPrice.getText().trim();

         if (customerName.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            double price = Double.parseDouble(priceText);
            String summary = "Customer Name: " + customerName + "\n"
                           + "Product: " + product + "\n"
                           + String.format("Price: R %.2f", price);
            JOptionPane.showMessageDialog(this, summary, "Order Details", JOptionPane.INFORMATION_MESSAGE);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonProcessActionPerformed

