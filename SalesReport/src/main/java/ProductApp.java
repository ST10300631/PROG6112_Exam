    private void jSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jSaveActionPerformed
        String customerName = txtCustomerName.getText().trim();
        String product = jComboBoxProduct.getSelectedItem().toString();
        String priceText = txtPrice.getText().trim();

        if (customerName.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields before saving.", "Save Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            double price = Double.parseDouble(priceText);
            try (FileWriter writer = new FileWriter("orders.txt", true)) {
                writer.write("Customer: " + customerName + " | Product: " + product + String.format(" | Price: R %.2f%n", price));
                JOptionPane.showMessageDialog(this, "Saved successfully to orders.txt!", "Saved", JOptionPane.INFORMATION_MESSAGE);
            } catch (IOException ex) {
                JOptionPane.showMessageDialog(this, "Error writing to file: " + ex.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
         
    }//GEN-LAST:event_jSaveActionPerformed

